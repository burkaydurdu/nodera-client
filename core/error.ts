/** Error envelope returned by every Nodera service and the gateway. */
export interface ApiError {
  code: number;
  domain: number;
  message: string;
}

/** 400 responses carry an array of field errors instead of the envelope. */
export interface ValidationError {
  field: string;
  message: string;
}

