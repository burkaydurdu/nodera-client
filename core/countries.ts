export interface CountryOption {
  value: string;
  label: string;
}

/** Options for a select, sorted by the localized name. */
export function getCountryOptions(locale: Locale): CountryOption[] {
  const collator = new Intl.Collator(locale);
  return COUNTRIES.map((country) => ({
    value: country.code,
    label: country.names[locale],
  })).sort((a, b) => collator.compare(a.label, b.label));
}

export function getCountryName(code: string, locale: Locale): string {
  return COUNTRIES.find((country) => country.code === code)?.names[locale] ?? code;
}

export function isCountryCode(code: string): boolean {
  return COUNTRIES.some((country) => country.code === code);
}
